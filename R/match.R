#' Match 990-PF grant recipients to the BMF
#'
#' Wraps [npmatch::np_cascade()] for the grant-recipient problem. The only
#' structural difference from the npmatch/SAM setup is the blocking cascade: a
#' foundation and its grantees need not share a state, so no pass keys on
#' geography.
#'
#' @name pf_match
NULL
#' Blocking passes with no geographic key
#'
#' npmatch's default cascade blocks every pass on `state` and only opens up to a
#' cross-state token pass at the end. That is right when query and reference are
#' the same establishment; it is wrong here, because a New York foundation
#' routinely funds a California charity and the address the filer types is
#' whatever was on the check — sometimes the grantee's HQ, sometimes a program
#' site, sometimes a lockbox. Every pass below is therefore state-free.
#'
#' Note that "no blocking" cannot mean a full cross product: 5,000 grants against
#' 1.9M BMF rows is 9.6 billion pairs. What is dropped is *geographic* blocking.
#' Candidates are still generated by exact name keys and by a shared distinctive
#' name token (IDF-pruned), which is a recall device rather than a geographic
#' constraint — state is used only downstream, as scoring evidence.
#'
#' @param max_ref_freq,min_pair_idf Token-pruning parameters for the loose pass.
#'   Defaults follow npmatch's cross-state pass: a lone shared token must occur
#'   in no more than ~645 of 1.9M BMF records to justify a pair on its own.
#' @return A list of pass specifications for [npmatch::np_cascade()].
#' @keywords internal
#' @export
pf_default_passes <- function(max_ref_freq = 5000, min_pair_idf = 8) {
  ex <- function(name, desc, x, y)
    list(name = name, desc = desc,
         args = list(by = NULL, by_x = x, by_y = y, token = FALSE))
  list(
    ex("exact-name",     "name == name (exact, any state)", "name_key", "name_key"),
    ex("exact-name-dba", "name == dba  (exact, any state)", "name_key", "dba_key"),
    ex("exact-dba-name", "dba == name  (exact, any state)", "dba_key",  "name_key"),
    ex("exact-dba-dba",  "dba == dba   (exact, any state)", "dba_key",  "dba_key"),
    list(name = "token-any", desc = "shared distinctive token, any state",
         args = list(by = NULL, token = TRUE, concat_adjacent = TRUE,
                     max_ref_freq = max_ref_freq, min_pair_idf = min_pair_idf))
  )
}
#' Staged cascade: state-blocked bulk, then an unblocked residual sweep
#'
#' The production shape for the full file. `pf_default_passes()` blocks nothing
#' geographically, which is the right instrument for *measuring* geographic
#' mismatch but is unaffordable at 12.5M grants: its cross-state token pass
#' compares against all 1.9M BMF records and accounts for 96% of the runtime.
#'
#' This cascade splits into three stages, tightest first. Because
#' [npmatch::np_cascade()] prunes only queries that reached **YES**, everything
#' unresolved — including every MAYBE — falls through to the next stage, so
#' blocking early costs recall only for records the later stages also miss.
#'
#' @section Stage A — state-blocked exact (very cheap):
#' Exact name against exact ZIP5, then against state, then the name/DBA
#' cross-products within state. ZIP5 implies state, so the first pass needs no
#' separate state key.
#'
#' @section Stage B — state-blocked token (moderate):
#' Shared distinctive name token within state, then the same with adjacent-token
#' compounds. This is where the bulk of the fuzzy work happens, against ~1/15th
#' of the reference rather than all of it.
#'
#' @section Stage C — unblocked residual sweep (expensive, small N):
#' Only the queries still unresolved reach here. This is what makes the state
#' block safe: it recovers the cases state blocking cannot see — a 990-PF state
#' field that is simply wrong (six of the ten cross-state YES matches in the
#' benchmark had matching city *and* ZIP but a wrong state code), a national
#' headquarters address in the BMF against a local grantee address, a lockbox,
#' and every record whose state is missing entirely (a blocked pass drops those,
#' since `.np_bykey()` treats an incomplete key as invalid).
#'
#' @section Choosing `sweep`:
#' Measured on 5,000 grants, the unblocked **token** sweep (`C3`) generated
#' 686,380 candidate pairs — 59% of the entire run — and produced **zero**
#' additional YES matches; its only product is MAYBE candidates for adjudication.
#' The four YES matches stage C did contribute all came from the cheap exact
#' pass `C1`, and three of those four are the known cross-state false positives
#' (`UNBOUND` MO->KS, `FIRST PRESBYTERIAN CHURCH` IA->NC, `PATTERSON VOLUNTEER
#' FIRE DEPARTMENT` LA->NC) — common names matched in another state with no
#' address corroboration.
#'
#' The cross-state cases that are *genuine* — a 990-PF state field simply typed
#' wrong, with city and ZIP both correct — never needed an unblocked sweep at
#' all: pass `A1` blocks on name + ZIP5 and deliberately carries **no state key**,
#' so it catches them at a fraction of the cost.
#'
#' * `"lean"` (default) — stages A and B plus the cheap exact cross-state passes.
#'   Same YES set, roughly half the candidates.
#' * `"full"` — adds the unblocked token sweep. Use when maximising the
#'   adjudication queue matters more than runtime.
#' * `"none"` — state-blocked only. Fastest; gives up the state-typo recovery
#'   that `A1` cannot reach (a wrong state *and* a wrong ZIP).
#'
#' @param sweep How much of the unblocked residual sweep to run (see above).
#' @param concat Include the adjacent-token compound pass `B2`, which recovers
#'   de-spacing differences (`STEP FORWARD` vs `STEPFORWARD`). Measured cost on
#'   5,000 grants: 223,151 candidates — 46% of the whole lean cascade — for 48
#'   YES matches. Keep it when recall matters more than runtime; drop it for a
#'   fast first pass over the full file, since most of what it finds degrades to
#'   MAYBE rather than disappearing.
#' @param max_ref_freq_state,min_pair_idf_state Token pruning inside a state.
#' @param max_ref_freq_any,min_pair_idf_any Token pruning for the unblocked
#'   sweep, tighter because the pool is the whole BMF.
#' @return A list of pass specifications for [npmatch::np_cascade()].
#' @export
pf_staged_passes <- function(sweep = c("lean", "full", "none"), concat = TRUE,
                             max_ref_freq_state = 25000, min_pair_idf_state = 8,
                             max_ref_freq_any = 5000, min_pair_idf_any = 8) {
  sweep <- match.arg(sweep)
  ex <- function(name, desc, x, y)
    list(name = name, desc = desc,
         args = list(by = NULL, by_x = x, by_y = y, token = FALSE))
  # the optional passes below evaluate to NULL when switched off; strip them so
  # np_cascade() never sees an empty spec
  Filter(Negate(is.null), c(
    # ---- Stage A: state-blocked exact ------------------------------------
    list(
      ex("A1-name-zip5",  "name + ZIP5 (exact)",        c("name_key", "zip5"), c("name_key", "zip5")),
      ex("A2-name-state", "name + state (exact)",       c("name_key", "state"), c("name_key", "state")),
      ex("A3-name-dba",   "name == dba, same state",    c("name_key", "state"), c("dba_key", "state")),
      ex("A4-dba-name",   "dba == name, same state",    c("dba_key", "state"),  c("name_key", "state")),
      ex("A5-dba-dba",    "dba == dba, same state",     c("dba_key", "state"),  c("dba_key", "state"))
    ),
    # ---- Stage B: state-blocked token ------------------------------------
    list(
      list(name = "B1-token-state", desc = "shared token, same state",
           args = list(by = "state", token = TRUE,
                       max_ref_freq = max_ref_freq_state,
                       min_pair_idf = min_pair_idf_state)),
      if (concat) list(name = "B2-token-concat", desc = "shared token + compound, same state",
           args = list(by = "state", token = TRUE, concat_adjacent = TRUE,
                       max_ref_freq = max_ref_freq_state,
                       min_pair_idf = min_pair_idf_state))
    ),
    # ---- Stage C: unblocked residual sweep -------------------------------
    if (sweep == "none") list() else list(
      ex("C1-name-any", "name == name, ANY state", "name_key", "name_key"),
      ex("C2-dba-any",  "name == dba,  ANY state", "name_key", "dba_key")
    ),
    if (sweep == "full") list(
      list(name = "C3-token-any", desc = "shared token + compound, ANY state",
           args = list(by = NULL, token = TRUE, concat_adjacent = TRUE,
                       max_ref_freq = max_ref_freq_any,
                       min_pair_idf = min_pair_idf_any))
    ) else list()
  ))
}
#' Which cascade stage produced each pass
#'
#' @param pass Character vector of pass names from a `pf_staged_passes()` run.
#' @return `"A"`, `"B"`, `"C"`, or `NA`.
#' @keywords internal
#' @export
pf_pass_stage <- function(pass) {
  s <- substr(as.character(pass), 1, 1)
  ifelse(s %in% c("A", "B", "C"), s, NA_character_)
}
#' Build the BMF reference once
#'
#' Normalization, the name-frequency table, the token-IDF table, and the
#' blocking index are all functions of the reference alone, so they are computed
#' once here and reused across every pass, batch, and experiment. This is
#' **preprocessing** and is excluded from the match timings reported by
#' [pf_match_grants()].
#'
#' @param bmf The raw processed BMF data frame (or a path to its CSV).
#' @param active_col Optional column flagging BMF-active EINs (for the unified
#'   BMF). Omit for the active-only file.
#' @return A list with the normalized `reference`, `name_freq`, `token_idf`, and
#'   `ref_index`, plus the elapsed seconds each stage took.
#' @export
pf_build_reference <- function(bmf, active_col = NULL) {
  tic <- function() proc.time()[["elapsed"]]
  t0 <- tic()
  if (is.character(bmf) && length(bmf) == 1L)
    bmf <- data.table::fread(bmf, colClasses = list(character = "ein"),
                             showProgress = FALSE)
  t_read <- tic() - t0
  t0 <- tic()
  ref <- npmatch::np_reference(bmf, npmatch::np_map_bmf(active_col = active_col))
  ref <- npmatch::np_normalize(ref)
  t_norm <- tic() - t0
  t0 <- tic()
  name_freq <- npmatch::np_name_freq(ref$name_key)
  token_idf <- npmatch::np_token_idf(ref$name_key)
  ref_index <- npmatch::np_ref_index(ref)
  t_index <- tic() - t0
  list(reference = ref, name_freq = name_freq, token_idf = token_idf,
       ref_index = ref_index,
       timing = c(read = t_read, normalize = t_norm, index = t_index))
}
#' Run the grant-recipient match
#'
#' Splits the prepared grants into in-scope and out-of-sample (see
#' [pf_oos_details()]), runs the cascade on the in-scope side only, and reports
#' the elapsed time of the match itself.
#'
#' The timing covers the cascade only — blocking, comparison, scoring, veto,
#' selection, tiering. Reading and normalizing the BMF, and preparing the grant
#' extract, are excluded (do them once via [pf_build_reference()] /
#' [pf_prepare_grants()]).
#'
#' @param grants A prepared frame from [pf_prepare_grants()].
#' @param ref A reference bundle from [pf_build_reference()], or a normalized
#'   `np_reference`.
#' @param config An [npmatch::np_config()].
#' @param method Scoring method passed to [npmatch::np_score()].
#' @param passes Blocking passes; defaults to [pf_default_passes()].
#' @param recover Add the stage-4 acronym and prefix blocking keys to both sides
#'   before matching. Required by [pf_recovery_passes()]; harmless otherwise, but
#'   it costs a pass over both frames, so it is `FALSE` by default.
#' @param verbose Print the per-stage cascade report.
#' @return A `pf_match` object: the `np_tiered` result plus the in-scope /
#'   out-of-scope split, the per-stage table, and timings.
#' @export
pf_match_grants <- function(grants, ref, config = npmatch::np_config(),
                            method = "hier", passes = pf_default_passes(),
                            recover = FALSE, verbose = TRUE) {
  stopifnot(!is.null(grants$in_scope), !is.null(grants$grant_id))
  bundle <- if (is.list(ref) && !is.null(ref$reference)) ref
            else list(reference = ref, name_freq = NULL, token_idf = NULL,
                      ref_index = NULL)
  q_in  <- grants[grants$in_scope, , drop = FALSE]
  q_out <- grants[!grants$in_scope, , drop = FALSE]
  if (!nrow(q_in)) stop("no in-scope grants to match.", call. = FALSE)
  # query canonicalization is cheap but is still preprocessing -- time it apart
  t0 <- proc.time()[["elapsed"]]
  query <- npmatch::np_query(q_in, pf_map_grants())
  if (recover) {
    # stage-4 keys must exist on BOTH sides before the cascade runs. Normalizing
    # the query here is safe: np_cascade() normalizes again and np_normalize()
    # only adds columns, so name_acro / name_pre survive.
    # np_query() maps row-for-row, so q_in's truncation flag lines up positionally
    trunc <- if (!is.null(q_in$name_truncated)) q_in$name_truncated else NULL
    query <- pf_add_recovery_keys(npmatch::np_normalize(query),
                                  only_truncated = trunc)
    if (is.null(bundle$reference$name_acro))
      bundle$reference <- pf_add_recovery_keys(bundle$reference)
  }
  t_prep <- proc.time()[["elapsed"]] - t0
  # ------------------------- TIMED MATCH WINDOW ---------------------------
  t0 <- proc.time()[["elapsed"]]
  res <- npmatch::np_cascade(
    query, bundle$reference, config = config, method = method,
    passes = passes, verbose = verbose,
    name_freq = bundle$name_freq, token_idf = bundle$token_idf,
    ref_index = bundle$ref_index)
  t_match <- proc.time()[["elapsed"]] - t0
  # ------------------------------------------------------------------------
  structure(
    list(result = res,
         grants = grants,
         in_scope = q_in$grant_id,
         out_of_scope = q_out$grant_id,
         stages = attr(res, "stages"),
         config = config,
         timing = c(query_prep = t_prep, match = t_match,
                    match_per_1k = t_match / nrow(q_in) * 1000),
         n = c(grants = nrow(grants), in_scope = nrow(q_in),
               out_of_scope = nrow(q_out),
               reference = nrow(bundle$reference))),
    class = "pf_match")
}
#' @export
print.pf_match <- function(x, ...) {
  s <- pf_status(x)
  tb <- table(factor(s$status, pf_status_levels()))
  cat("<pf_match>\n")
  cat(sprintf("  grants: %s (%s in scope, %s out of sample)\n",
              format(x$n[["grants"]], big.mark = ","),
              format(x$n[["in_scope"]], big.mark = ","),
              format(x$n[["out_of_scope"]], big.mark = ",")))
  cat(sprintf("  reference: %s BMF records\n", format(x$n[["reference"]], big.mark = ",")))
  cat(sprintf("  outcome: %d YES | %d MAYBE | %d NO | %d OOS\n",
              tb[["YES"]], tb[["MAYBE"]], tb[["NO"]], tb[["OOS"]]))
  cat(sprintf("  match time: %.1f s (%.1f s per 1,000 in-scope grants)\n",
              x$timing[["match"]], x$timing[["match_per_1k"]]))
  invisible(x)
}
